import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('cinematic opening, all sections and reversible journey', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/')
  await expect(page.locator('.loading-screen')).toHaveCount(0, { timeout: 15000 })
  await expect(page.getByRole('heading', { level: 1 })).toContainText('A lifetime begins')
  await page.screenshot({ path: testInfo.outputPath('desktop.png') })
  await page.getByRole('button', { name: 'Open Invitation', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Enter Our Celebration', exact: true })).toBeEnabled({ timeout: 6000 })
  await page.screenshot({ path: testInfo.outputPath('opened-card.png') })
  await page.getByRole('button', { name: 'Enter Our Celebration', exact: true }).click()
  await expect(page.locator('.portal-transition')).toHaveCount(0, { timeout: 6000 })
  await page.waitForTimeout(700)
  await page.screenshot({ path: testInfo.outputPath('temple-journey.png') })
  const journeyTop = await page.locator('#journey').evaluate(element => element.getBoundingClientRect().top + window.scrollY)
  await page.evaluate(top => window.scrollTo({ top: top + 1200, behavior: 'instant' }), journeyTop)
  await page.waitForTimeout(800)
  await page.evaluate(top => window.scrollTo({ top, behavior: 'instant' }), journeyTop)
  await page.waitForTimeout(1200)
  await expect(page.locator('.journey-copy')).toHaveCSS('opacity', '1')
  for (const id of ['couple', 'story', 'events', 'venue', 'gallery', 'rsvp', 'blessings']) {
    await page.locator(`#${id}`).scrollIntoViewIfNeeded()
    await expect(page.locator(`#${id} h2`)).toBeVisible()
  }
  expect(await page.locator('.event-card').count()).toBe(6)
  expect(await page.locator('.initial-portrait').count()).toBe(2)
  expect(await page.locator('.gallery-tile .gallery-placeholder').count()).toBe(5)
  await page.locator('#couple').scrollIntoViewIfNeeded(); await page.waitForTimeout(500)
  await page.screenshot({ path: testInfo.outputPath('couple.png') })
  expect(errors).toEqual([])
})

test('responsive layouts, reduced motion and Tamil navigation', async ({ page }, testInfo) => {
  const requested: string[] = []
  page.on('request', request => requested.push(request.url()))
  await page.emulateMedia({ reducedMotion: 'reduce' })
  for (const width of [320, 390, 768, 1024, 1920]) {
    await page.setViewportSize({ width, height: 900 })
await page.goto('/')
  await expect(page.locator('.loading-screen')).toHaveCount(0, { timeout: 30000 })
    expect(await page.locator('canvas').count()).toBe(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    if (width === 390) await page.screenshot({ path: testInfo.outputPath('mobile.png') })
    for (const id of ['couple', 'events', 'venue', 'gallery', 'rsvp']) {
      await page.locator(`#${id}`).scrollIntoViewIfNeeded()
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    }
  }
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'தமிழ்', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('lang', 'ta')
  await page.getByRole('button', { name: 'வழிசெலுத்தலைத் திற', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('dialog').getByRole('link', { name: 'மணமக்கள்', exact: true }).click()
  await expect(page).toHaveURL(/#couple$/)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.locator('#home').scrollIntoViewIfNeeded()
  await page.screenshot({ path: testInfo.outputPath('tamil.png') })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(requested.some(url => /three-engine|three-react|InvitationScene|TempleJourney/.test(url))).toBe(false)
})

test('RSVP, local persistence, blessings, gallery and sharing', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await expect(page.locator('.loading-screen')).toHaveCount(0, { timeout: 15000 })
  await page.getByRole('button', { name: 'Send My RSVP', exact: true }).click()
  await expect(page.locator('#rsvp-name-error')).toBeVisible()
  await expect(page.locator('#rsvp-name')).toBeFocused()
  await page.locator('#rsvp-name').fill('Arun & Meena')
  await page.locator('#rsvp-phone').fill('+91 98765 43210')
  await page.getByLabel('Joyfully accept', { exact: true }).check()
  await page.locator('#rsvp-guests').selectOption('3')
  await page.locator('#rsvp-message').fill('Wishing you a wonderful life together!')
  await page.getByRole('button', { name: 'Send My RSVP', exact: true }).click()
  await expect(page.locator('.rsvp-success')).toContainText('Your response is ready')
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('wedding-rsvp-v1') ?? '{}') as { guests: number; name: string })
  expect(saved.guests).toBe(3); expect(saved.name).toBe('Arun & Meena')
  await page.locator('#blessing-name').fill('Arun')
  await page.locator('#blessing-message').fill('May your home be filled with love, joy, and jasmine.')
  await page.getByRole('button', { name: 'Leave a Blessing', exact: true }).click()
  await expect(page.locator('.blessing-card')).toContainText('May your home be filled')
  await page.reload()
  await expect(page.locator('#rsvp-name')).toHaveValue('Arun & Meena')
  await expect(page.locator('.blessing-card')).toHaveCount(1)
  await page.locator('.gallery-tile').first().click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('ArrowRight')
  await expect(page.locator('.lightbox-controls')).toContainText('Our kind of forever')
  await page.keyboard.press('ArrowLeft')
  await expect(page.locator('.lightbox-controls')).toContainText('The beginning of everything')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('.gallery-tile').first()).toBeFocused()
  await page.getByRole('button', { name: 'Get Directions', exact: true }).click()
  await expect(page.locator('.toast')).toContainText('Location details will be shared soon')
  await page.getByRole('button', { name: 'Google Calendar', exact: true }).click()
  await expect(page.locator('.toast')).toContainText('The date will be announced soon')
  const share = page.getByRole('link', { name: 'WhatsApp', exact: true })
  expect(await share.getAttribute('href')).toContain('https://wa.me/?text=')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download Invite', exact: true }).click()
  expect((await download).suggestedFilename()).toBe('karthi-wedding-invitation.png')
})

test('WCAG accessibility checks on the complete invitation', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await expect(page.locator('.loading-screen')).toHaveCount(0, { timeout: 15000 })
  const report = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(report.violations.map(violation => ({ id: violation.id, impact: violation.impact, elements: violation.nodes.map(node => ({ selector: node.target, summary: node.failureSummary })) }))).toEqual([])
})

test('unavailable WebGL, native history and session audio choice', async ({ page }) => {
  await page.addInitScript(() => {
    sessionStorage.setItem('wedding-muted', 'true')
    const original = HTMLCanvasElement.prototype.getContext
    HTMLCanvasElement.prototype.getContext = new Proxy(original, { apply(target, receiver, args: unknown[]) { return args[0] === 'webgl2' ? null : Reflect.apply(target, receiver, args) } })
  })
  await page.goto('/')
  await expect(page.locator('.loading-screen')).toHaveCount(0, { timeout: 15000 })
  await expect(page.locator('.gentle-experience')).toHaveCount(1)
  await expect(page.locator('canvas')).toHaveCount(0)
  await page.getByRole('button', { name: 'Open Invitation', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Enter Our Celebration', exact: true })).toBeEnabled()
  await expect(page.getByRole('button', { name: 'Play music', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await page.getByRole('button', { name: 'Play music', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Mute music', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Music settings', exact: true }).click()
  await page.getByRole('button', { name: 'Stop music', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Play music', exact: true })).toBeVisible()
  await page.locator('.desktop-nav').getByRole('link', { name: 'The Couple', exact: true }).click()
  await expect(page).toHaveURL(/#couple$/)
  await page.locator('.desktop-nav').getByRole('link', { name: 'Gallery', exact: true }).click()
  await expect(page).toHaveURL(/#gallery$/)
  await page.goBack()
  await expect(page).toHaveURL(/#couple$/)
  await page.goForward()
  await expect(page).toHaveURL(/#gallery$/)
})
