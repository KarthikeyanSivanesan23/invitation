import { test, expect } from '@playwright/test'

test('detailed temple: aerial, approach, mandapam and illuminated night', async ({ page }, testInfo) => {
  test.setTimeout(90000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/')
  await expect(page.locator('.loading-screen')).toHaveCount(0, { timeout: 30000 })
  const journey = await page.locator('#journey').evaluate(element => ({ top: element.getBoundingClientRect().top + window.scrollY, distance: element.clientHeight - window.innerHeight }))
  await page.evaluate(top => window.scrollTo({ top, behavior: 'instant' }), journey.top + 100)
  await expect(page.locator('.journey-canvas canvas')).toHaveCount(1)
  await page.waitForTimeout(2500)
  await page.screenshot({ path: testInfo.outputPath('temple-aerial.png') })
  await page.evaluate(top => window.scrollTo({ top, behavior: 'instant' }), journey.top + journey.distance * .38)
  await page.waitForTimeout(2000)
  await page.screenshot({ path: testInfo.outputPath('temple-approach.png') })
  await page.evaluate(top => window.scrollTo({ top, behavior: 'instant' }), journey.top + journey.distance * .8)
  await page.waitForTimeout(2000)
  await page.screenshot({ path: testInfo.outputPath('temple-entrance.png') })
  await page.locator('.mandapam-section').scrollIntoViewIfNeeded()
  await expect(page.locator('.mandapam-visual canvas')).toHaveCount(1)
  await page.waitForTimeout(1800)
  await page.screenshot({ path: testInfo.outputPath('mandapam.png') })
  await page.locator('.closing-scene').scrollIntoViewIfNeeded()
  await expect(page.locator('.closing-canvas canvas')).toHaveCount(1)
  await page.waitForTimeout(2000)
  await page.screenshot({ path: testInfo.outputPath('temple-night.png') })
  expect(errors).toEqual([])
})

test('detailed temple remains available on a phone viewport', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.locator('.loading-screen')).toHaveCount(0, { timeout: 15000 })
  const top = await page.locator('#journey').evaluate(element => element.getBoundingClientRect().top + window.scrollY)
  await page.evaluate(y => window.scrollTo({ top: y + 150, behavior: 'instant' }), top)
  await expect(page.locator('.journey-canvas canvas')).toHaveCount(1)
  await page.waitForTimeout(2500)
  await page.screenshot({ path: testInfo.outputPath('temple-mobile.png') })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
